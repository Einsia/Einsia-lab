/** Export only the project page, its assets, and referenced Astro bundles. */
import { readFile, writeFile, mkdir, cp, stat, rm } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const dist = path.join(root, 'dist');
const output = path.join(root, 'dist-embodiedrsi');
const marker = path.join(output, '.embodiedrsi-export');
async function exists(p) { try { await stat(p); return true; } catch { return false; } }
if (await exists(output)) {
  if (!await exists(marker)) throw new Error('Refusing to replace an unrecognized output directory.');
  await rm(output, { recursive: true });
}
await mkdir(output, { recursive: true });
await writeFile(marker, 'Generated by scripts/export-embodiedrsi.mjs\n');
await cp(path.join(dist, 'embodied-rsi'), path.join(output, 'embodied-rsi'), { recursive: true });
const queue = ['index.html', 'embodied-rsi/index.html'];
const visited = new Set();
while (queue.length) {
  const relative = queue.shift();
  if (visited.has(relative)) continue;
  visited.add(relative);
  const source = path.resolve(dist, relative);
  if (!source.startsWith(dist + path.sep)) throw new Error(`Unexpected dependency: ${relative}`);
  const target = path.join(output, relative);
  await mkdir(path.dirname(target), { recursive: true });
  await cp(source, target);
  if (!/\.(?:html|css|js)$/.test(relative)) continue;
  const text = await readFile(source, 'utf8');
  // Astro emits absolute /_astro paths in HTML and CSS, and relative module imports.
  for (const match of text.matchAll(/(?:["'(])((?:\/_astro\/|\.\/)[^\s"')<>]+)["')]/g)) {
    const asset = match[1].split(/[?#]/)[0];
    const dependency = asset.startsWith('/') ? asset.slice(1) : path.normalize(path.join(path.dirname(relative), asset));
    if (await exists(path.join(dist, dependency))) queue.push(dependency);
    else throw new Error(`Missing dependency: ${dependency}`);
  }
}
await writeFile(path.join(output, 'robots.txt'), 'User-agent: *\nDisallow: /\n');
console.log(`Exported EmbodiedEvo with ${visited.size} HTML/bundle/font dependencies to ${output}`);
