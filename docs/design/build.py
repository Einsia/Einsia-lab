#!/usr/bin/env python3
"""Build the portable Lab design review draft using Python's standard library.

Inputs: review-notes.md, tokens.json, components.css, specimens.html,
        preview.js, document.css and document.js.
Outputs: tokens.css, lab-design-guideline.html.
The tiny Markdown renderer intentionally supports only the constructs used here.
"""
from pathlib import Path
import html
import json
import re

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
read = lambda name: (HERE / name).read_text(encoding="utf-8")


def inline(text):
    parts = []
    def code(match):
        parts.append("<code>" + html.escape(match[1]) + "</code>")
        return f"@@CODE{len(parts)-1}@@"
    text = re.sub(r"`([^`]+)`", code, text)
    text = html.escape(text)
    text = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", text)
    text = re.sub(r"https://[^\s，。；、）]+", lambda m: f'<a href="{m[0]}">{m[0]}</a>', text)
    for i, part in enumerate(parts):
        text = text.replace(f"@@CODE{i}@@", part)
    return text


def contrast(a, b):
    def luminance(color):
        channels = [int(color[i:i+2], 16)/255 for i in (1, 3, 5)]
        return sum((c/12.92 if c <= .04045 else ((c+.055)/1.055)**2.4)*w
                   for c, w in zip(channels, (.2126, .7152, .0722)))
    light, dark = sorted((luminance(a), luminance(b)), reverse=True)
    return (light+.05)/(dark+.05)


def main():
    config = json.loads(read("tokens.json"))
    values = config["tokens"]
    css = ["/* Generated by build.py from tokens.json. Do not edit directly. */", ":root {", "  color-scheme: light;"]
    for key, token in values.items():
        value = token["value"]
        if "alias" in token:
            value = f'var({token["alias"]}, {value})'
        css.append(f"  --lab-{key}: {value};")
    css.append("}\n")
    token_css = "\n".join(css)
    (HERE / "tokens.css").write_text(token_css, encoding="utf-8")

    # Check the brand aliases and all supported foreground/background pairings.
    global_css = (ROOT / "src/styles/global.css").read_text()
    for token in values.values():
        if "alias" in token:
            assert re.search(re.escape(token["alias"]) + r"\s*:\s*" + re.escape(token["value"]) + ";", global_css, re.I), token
    ratios = []
    for fg in ("text", "muted", "accent", "success", "warning", "danger"):
        for bg in ("bg", "surface", "selected", "figure-bg"):
            ratio = contrast(values[fg]["value"], values[bg]["value"])
            assert ratio >= 4.5, (fg, bg, ratio)
            ratios.append(ratio)
    for bg in ("accent", "accent-hover"):
        assert contrast(values["on-accent"]["value"], values[bg]["value"]) >= 4.5
    for bg in ("bg", "surface"):
        assert contrast(values["control-border"]["value"], values[bg]["value"]) >= 3

    components = read("components.css")
    used = set(re.findall(r"var\(--lab-([\w-]+)", components + read("document.css") + read("specimens.html")))
    assert used <= values.keys(), used - values.keys()
    fragments = dict(re.findall(r'<template id="([^"]+)">\s*(.*?)\s*</template>', read("specimens.html"), re.S))
    navbar = (ROOT / "src/components/navbar/navbar.astro").read_text()
    logo_path = re.search(r'<path\s+d="([^"]+)"', navbar)[1]
    fragments["BrandMark"] = f'<svg viewBox="0 0 24 24" fill="currentColor" aria-hidden="true"><path d="{logo_path}"></path></svg>'
    swatch_keys = ("bg", "text", "surface", "muted", "selected", "accent")
    fragments["Swatches"] = "".join(
        f'<div style="display:flex;gap:var(--lab-space-4);align-items:center"><span aria-hidden="true" style="display:block;width:var(--lab-space-12);height:var(--lab-space-12);flex:none;border:1px solid var(--lab-border);border-radius:var(--lab-radius-sm);background:var(--lab-{key})"></span><div><code>--lab-{key}</code><p class="lab-meta">{values[key]["value"]}</p></div></div>'
        for key in swatch_keys)

    def expand(name, trail=()):
        assert name not in trail, f"Cyclic partial: {name}"
        return re.sub(r"\{\{(\w+)\}\}", lambda m: expand(m[1], trail + (name,)), fragments[name])
    names = [name for name in fragments if not name.startswith("Partial") and name not in ("BrandMark", "Swatches")]
    templates = {name: expand(name) for name in names}
    for name, content in templates.items():
        ids = re.findall(r'\bid="([^"]+)"', content)
        assert len(ids) == len(set(ids)), (name, "Duplicate ids")
        assert 'href="#"' not in content
        for target in re.findall(r'href="#([^"]+)"', content):
            assert target in ids, (name, "Missing anchor", target)

    labels = {"Palette":"品牌与语义颜色", "Type":"字体层级", "Controls":"操作与表单", "ResearchRow":"Research 项目行", "Evidence":"研究图表与引用", "States":"必要的界面状态", "Project":"A · 项目介绍", "Results":"B · 结果页", "Explorer":"C · 案例浏览", "Article":"D · 方法长文"}
    def specimen(name):
        assert name in templates, name
        return f'''<div class="doc-preview" data-preview="{name}">
<div class="doc-preview-bar"><span class="doc-preview-name">{labels[name]}</span><div class="doc-preview-controls" role="group" aria-label="Preview width">
<button type="button" data-width="fit" aria-pressed="true">适应宽度</button><button type="button" data-width="1280" aria-pressed="false">1280px</button><button type="button" data-width="390" aria-pressed="false">390px</button><button type="button" data-download-template>下载示例</button></div></div>
<div class="doc-frame-host"><div class="doc-frame-shell"><iframe title="{labels[name]} reference" loading="lazy"></iframe></div></div>
<details class="doc-source"><summary>查看结构 · markup-{name}</summary><pre><code>{html.escape(templates[name])}</code></pre></details></div>'''

    md = read("review-notes.md")
    headings = re.findall(r"^## (.+?) \{#([\w-]+)\}$", md, re.M)
    assert len(headings) == len({anchor for _, anchor in headings})
    out, paragraph, list_type = [], [], None
    section_open = False
    def flush():
        nonlocal list_type
        if paragraph:
            out.append("<p>" + inline(" ".join(paragraph)) + "</p>")
            paragraph.clear()
        if list_type:
            out.append(f"</{list_type}>")
            list_type = None
    for line in md.splitlines():
        if line.startswith("# "):
            continue
        h = re.match(r"## (.+?) \{#([\w-]+)\}$", line)
        marker = re.match(r"<!-- specimen:(\w+) -->", line)
        bullet = re.match(r"(?:- |\d+\. )(.+)", line)
        if h:
            flush()
            if section_open:
                out.append("</section>")
            out.append(f'<section class="doc-section" id="{h[2]}"><h2>{inline(h[1])}</h2>')
            section_open = True
        elif marker:
            flush()
            out.append(specimen(marker[1]))
        elif bullet:
            kind = "ul" if line.startswith("- ") else "ol"
            if list_type != kind:
                flush()
                out.append(f"<{kind}>")
                list_type = kind
            text = bullet[1]
            if text.startswith("[ ] "):
                text = "□ " + text[4:]
            out.append("<li>" + inline(text) + "</li>")
        elif not line.strip():
            flush()
        else:
            paragraph.append(line)
    flush()
    if section_open:
        out.append("</section>")
    body = "\n".join(out)
    toc = '<nav aria-label="评审目录">' + "".join(f'<a href="#{anchor}">{html.escape(label)}</a>' for label, anchor in headings) + '</nav>'
    token_rows = "".join(f'<div class="doc-token"><code>--lab-{key}</code><code>{html.escape(token["value"])}</code><p>{html.escape(token.get("use", "Shared scale"))}</p></div>' for key, token in values.items())
    embedded_templates = "\n".join(f'<template id="markup-{name}">\n{value}\n</template>' for name, value in templates.items())
    # These curated inputs must be safe to store as raw-text script blocks.
    for source in (read("preview.js"), read("tokens.json")):
        assert "</script" not in source.lower()
    output = f'''<!doctype html>
<!-- Design review draft. Proposed visual direction, not an approved project standard. Generated by docs/design/build.py. -->
<html lang="zh-CN"><head><meta charset="UTF-8"><meta name="viewport" content="width=device-width, initial-scale=1"><meta name="color-scheme" content="light"><title>Lab design guideline · 设计评审草案</title>
<style id="ds-tokens">{token_css}</style><style>{read("document.css")}</style>
<script type="application/json" id="ds-tokens-json">{read("tokens.json")}</script>
<script type="text/plain" id="ds-components">{components}</script>
<script type="text/plain" id="ds-preview-js">{read("preview.js")}</script></head>
<body><aside class="doc-side"><a class="doc-brand" href="#top">{fragments["BrandMark"]}Navers lab</a><p class="doc-edition">Design review · v{config["version"]}<br>待设计评审</p>{toc}<details class="doc-mobile-nav"><summary>浏览评审目录</summary>{toc}</details></aside>
<main class="doc-main" id="top"><header class="doc-hero"><div class="doc-topline"><span>Einsia / Lab</span><span>评审草案 v{config["version"]} · November 2026</span></div><h1>Lab design guideline</h1><p class="doc-lead">让研究成为主角。<br>统一页面语言，保留内容的个性。</p><div class="doc-actions"><a class="doc-button doc-button-primary" href="#p-project">查看页面模板 ↓</a><a class="doc-button" href="#f-colour">查看颜色与字体</a><a class="doc-button" href="#review-checklist">评审清单</a></div><p class="doc-status" id="doc-status">待设计评审 · 以下方向与参数均为提案，尚未定稿</p></header>
<div class="doc-prose">{body}</div>
<section class="doc-downloads" id="proposed-tokens"><h2>拟议 Token 参数</h2><p>这些参数用于本次视觉示例，供设计逐项确认或调整。每个示例可单独下载为 HTML，方便查看。</p><details class="doc-source"><summary>全部拟议 token 与用途 · {len(values)} 个</summary><div class="doc-token-list">{token_rows}</div></details></section>
<footer class="doc-foot">Navers lab · Design review v{config["version"]} · 2026-11-27<br>本文件为设计评审草案。根据设计反馈修订后，再确认最终规范。</footer></main>
{embedded_templates}
<script>{read("document.js")}</script></body></html>'''
    (HERE / "lab-design-guideline.html").write_text(output, encoding="utf-8")
    print(f"Built lab-design-guideline.html ({len(output.encode()):,} bytes), tokens.css; {len(headings)} sections, {len(templates)} specimens, {len(values)} tokens.")
    print(f"Brand aliases, anchors and token references verified. Minimum supported text contrast: {min(ratios):.2f}:1.")


if __name__ == "__main__":
    main()
